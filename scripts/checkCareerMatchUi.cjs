    await page.getByText("We can keep using your CV and current criteria. Tell me what you'd like to look for next.", { exact: true }).waitFor();
    await send("Marketing analyst"); await firstResult("Marketing analyst");
    check(await count("analysis") === 1, "new search keeps paid CV analysis");
    check(await page.getByText("Location: Leeds", { exact: true }).isVisible());
