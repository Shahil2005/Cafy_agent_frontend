    check(await count("analysis") === 0);
    check(await page.locator('[aria-label="CAFY career conversation"]').evaluate((el) => el.classList.contains("ph-sensitive") && el.classList.contains("ph-no-capture") && el.classList.contains("sentry-block") && el.hasAttribute("data-ph-no-capture") && el.hasAttribute("data-sentry-block")));
    await page.screenshot({ path: path.join(output, "CAFY_CHAT_ENGINE_START.png"), fullPage: true });
    await page.getByRole("button", { name: "Use Example graduate CV.pdf", exact: true }).click();
    check(await count("analysis") === 0, "choosing a CV is not consent to analyse it");
    check(await page.getByText(/process its text with CAFY's AI provider.*never your CV/).isVisible());
    await page.getByRole("button", { name: "Yes, use this CV", exact: true }).click();
    await firstResult();
    check(await page.getByRole("article").count() === 5);
    check(await count("analysis") === 1);
    check(await page.getByRole("article").first().getByText("Picked from your CV review", { exact: true }).isVisible());
    check(await page.getByText("Compare CV and advert evidence", { exact: true }).count() === 0, "cards do not list line-by-line comparisons");
    await page.screenshot({ path: path.join(output, "CAFY_CHAT_ENGINE_RESULTS.png"), fullPage: true });
