    await page.getByRole("button", { name: "Retry this search", exact: true }).click(); await firstResult();
    check(await count("analysis") === 1 && await count("context") === 1);
    await scenario("next-outage"); await useSaved(); await firstResult();
    await send("more"); await page.getByRole("button", { name: "Retry this search", exact: true }).waitFor();
    check(await page.getByRole("article").count() === 5);
    await send("retry");
    await page.waitForFunction(() => Number(document.querySelector('[data-testid="fixture-counts"]').dataset.next) === 2);
    check(await page.getByRole("alert").count() === 0, "repeated empty outages are not duplicate-job failures");
    check(await page.getByRole("article").count() === 5);
    await page.getByRole("button", { name: "Retry this search", exact: true }).waitFor();
    await send("retry"); await firstResult("Software Developer", 6);
    check(await page.getByRole("article").count() === 5);
    check(await count("analysis") === 1 && await count("next") === 3 && await count("context") === 0, "failed pagination retries the same continuation");
    await scenario("expired"); await useSaved(); await firstResult();
    await send("only in Leeds");
    await page.getByText("This matching session has expired. Confirm your CV again when you're ready, and I'll start a fresh search.", { exact: true }).waitFor();
    check(await count("analysis") === 1);
    check(await page.getByRole("button", { name: "Yes, use this CV", exact: true }).isVisible());
    await page.getByRole("button", { name: "Yes, use this CV", exact: true }).click(); await firstResult();
    check(await count("analysis") === 2, "expired CV is analysed again only after explicit confirmation");
    await scenario("duplicate"); await useSaved(); await firstResult(); await send("more");
    await page.getByRole("alert").filter({ hasText: "repeated earlier opportunities" }).waitFor();
    check(await page.getByRole("article").count() === 5);
    await scenario("preferred");
    check(await page.getByRole("button", { name: "Levels: Entry Level, Junior", exact: true }).isVisible());
    await useSaved(); await firstResult();
    check(await page.getByRole("article").first().getByText("Advert level: Entry Level", { exact: true }).isVisible());
