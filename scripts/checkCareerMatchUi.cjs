    const cardText = await cards.allInnerTexts();
    check(cardText.every((value) => !/requirements I checked|Not shown in your CV|Stretch|Partial|missing|lack/i.test(value)), "cards carry no line-by-line or negative copy");
    // The conversation scrolls inside its own panel, so bring the cards into view first.
    await cards.first().evaluate((el) => el.scrollIntoView({ block: "start" }));
    await page.screenshot({ path: path.join(output, "CAFY_CHAT_ENGINE_FIT_SCORES.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await cards.last().evaluate((el) => el.scrollIntoView({ block: "end" }));
    check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "fit scores fit a phone width");
    await page.screenshot({ path: path.join(output, "CAFY_CHAT_ENGINE_FIT_SCORES_MOBILE.png"), fullPage: true });
