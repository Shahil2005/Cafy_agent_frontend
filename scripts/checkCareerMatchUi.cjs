    check(await page.getByRole("article").count() === 5);
    check(await page.getByRole("status").filter({ hasText: "Cancelled." }).isVisible());
    await send("How should I structure my CV?");
    await page.getByText("Choose one real example from your experience and explain what you did and the result. Keep your CV truthful.", { exact: true }).waitFor();
    check(await count("advice") === 1);
    check(await count("analysis") === 1);
    await send("Why am I not getting interviews?");
    await page.waitForFunction(() => Number(document.querySelector('[data-testid="fixture-counts"]').dataset.advice) === 2);
    check(await count("advice") === 2);
    check(await count("analysis") === 1);
    check(await page.getByRole("article").count() === 5, "advice preserves the current shortlist");
    await send("Help me improve my CV error"); await page.getByRole("alert").waitFor();
