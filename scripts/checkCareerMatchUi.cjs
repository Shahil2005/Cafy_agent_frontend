    check(await page.getByRole("article").first().getByText("Advert level: Junior", { exact: true }).isVisible());
    check(await count("analysis") === 1);
    await page.getByRole("button", { name: "Levels: Junior", exact: true }).click();
    await page.getByRole("button", { name: "Any level", exact: true }).click();
    await page.getByRole("button", { name: "Levels: Any level", exact: true }).waitFor();
    check(await count("analysis") === 1);
    await scenario("late");
    await useSaved(); await firstResult();
    await page.getByRole("button", { name: "Load entry and junior preferences", exact: true }).click();
    await page.getByRole("button", { name: "Apply saved levels", exact: true }).waitFor();
    check(await page.getByRole("button", { name: "Levels: Any level", exact: true }).isVisible());
    check(await count("analysis") === 1 && await count("context") === 0, "late preferences await confirmation instead of drifting from the server context");
    await page.getByRole("button", { name: "Apply saved levels", exact: true }).click();
    await page.getByRole("button", { name: "Levels: Entry Level, Junior", exact: true }).waitFor();
    check(await count("analysis") === 1 && await count("context") === 1);
    await page.getByRole("button", { name: "Levels: Entry Level, Junior", exact: true }).click();
    await page.getByRole("button", { name: "Junior", exact: true }).click();
    await page.getByRole("button", { name: "Levels: Junior", exact: true }).waitFor();
    await page.getByRole("button", { name: "Load senior preferences", exact: true }).click();
    check(await page.getByRole("button", { name: "Levels: Junior", exact: true }).isVisible());
    await scenario("full-review"); await useSaved(); await firstResult();
    const review = page.getByLabel("Your CV review", { exact: true });
    check(await review.count() === 1);
    check(await review.getByRole("heading", { name: "I've reviewed the CV you chose.", exact: true }).isVisible());
    check(await review.getByText("Customer Support Assistant", { exact: true }).first().isVisible());
    check(await review.getByText("Student Budget Dashboard", { exact: true }).first().isVisible());
    check(await review.getByText("BSc Computer Science", { exact: true }).first().isVisible());
    check(await review.getByText("AWS Certified Cloud Practitioner", { exact: true }).first().isVisible());
    check(await review.getByText("Suggested search directions", { exact: true }).isVisible());
    check(await page.getByRole("article").count() === 5, "a confirmed CV returns the actual first five alongside its full review");
    await review.getByText("Read the full CV review", { exact: true }).click();
    check(await review.getByText("From your CV: “BSc Computer Science, Example University.”", { exact: true }).isVisible());
    await page.screenshot({ path: path.join(output, "CAFY_CHAT_ENGINE_CV_REVIEW.png"), fullPage: true });
    await send("more"); await firstResult("Software Developer", 6);
    check(await page.getByLabel("Your CV review", { exact: true }).count() === 1);
    check(await count("analysis") === 1);
    await scenario("web"); await useSaved();
    await page.getByText("Reviewing your whole CV, checking the catalogue and employer sites, and scoring each advert against your CV…", { exact: true }).waitFor();
    await firstResult();
    check(await count("web") === 1, "employer-source progress is tied to the explicit initial includeWeb request");
    check(await page.getByRole("article").count() === 5);
    check(await page.getByRole("article").filter({ hasText: "Example employer website" }).count() === 1);
    check(await page.getByRole("article").filter({ hasText: "Example government jobs service" }).count() === 1);
    check(await page.getByRole("article").last().getByText("Posting date not supplied", { exact: true }).isVisible());
    check(await page.getByRole("article").nth(3).getByText(/^Posted /).isVisible());
    check(await page.getByRole("article").nth(3).getByText(/^Closes /).isVisible());
    check(await page.getByRole("article").last().getByText(/Source checked .*confirm availability/).isVisible());
    check(await page.getByRole("article").last().getByRole("link", { name: "Read full advert", exact: true }).getAttribute("href") === "https://example.org/fictional-jobs/5");
    await page.getByText("Search details", { exact: true }).click();
    check(await page.getByText(/Checked 24 employer and government adverts across 2 supported sources/).isVisible());
