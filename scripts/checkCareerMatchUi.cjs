    await page.waitForFunction(() => document.querySelectorAll('[role="log"] p').length > 0 && [...document.querySelectorAll('[role="log"] p')].filter((element) => element.textContent === "You've seen the supported opportunities in this shortlist. What would you like to explore next?").length === 2);
